// ── 静态兜底表：**已按委托方要求删除**（2026-10-09）──
//
// ═══════════════════════════════════════════════════════════════════
// 🔴 为什么删（委托方原话，不要"好心"加回来）
// ═══════════════════════════════════════════════════════════════════
//
//	「我记得我的模型列表有静态表作为从上游获取失败时的兜底，赶紧将静态表删了，
//	  如果以后上游改动了，静态表的数据都是假数据，没有意义。」
//
// 这个判断是对的，而且比它表面上更对。被删掉的那张表长这样：
//
//	{UpstreamID: "gpt-6-astra",        Multiplier: 6.67}
//	{UpstreamID: "kimi-k2.8-preview",  Multiplier: 0.77}
//	{UpstreamID: "glm-5.3-flash",      Multiplier: 0.06}
//	...
//
// 它是 2026-10-06 从参考项目的 cache 里**一次性抄录**的倍率快照。
// 问题在于它的**触发时机**：只在 `/v3/config` 拉取失败时启用。
// 而"上游拉取失败"恰恰是最可能伴随"上游改了定价/下架了模型"的时刻 ——
// 于是这张表会在**最不该相信它的时候**被拿来当权威数据用：
//
//	· 上游把 gpt-6-astra 从 6.67 调成 2.00，同时 /v3 抖动一次
//	  ⇒ 面板显示 6.67，用户按假价格做决策
//	· 上游下架了某个模型，/v3 拉取失败
//	  ⇒ 静态表把它"复活"，用户选到调不通的模型
//	· 新增模型永远不会出现在这张表里
//	  ⇒ 兜底只可能"多给旧的、少给新的"，方向性偏差
//
// ⇒ 这是**假数据**，而且是会在关键时刻冒充真数据的假数据。
//    删掉之后：/v3 失败 ⇒ 国际版就少那 5 个模型的展示，
//    但显示的每一个数字都来自上游，**没有一个是编的**。
//
// ═══════════════════════════════════════════════════════════════════
// 删除后行为变化（如实记录，不是"没有代价"）
// ═══════════════════════════════════════════════════════════════════
//
//	`/v3/config` 不可用时，国际版模型列表**会少 5 个**（此前靠静态表补上）：
//	  deepseek-v4.1-flash / -sg / glm-5.3-flash /
//	  kimi-k2.8-preview / gpt-6-astra
//
//	⚠️ 这是**刻意接受的**取舍：宁可少列，不可假列。
//	实测（2026-10-09，本机真实上游）：/v3 正常时这 5 个模型**本来
//	就由上游给出**（ctx=1000000、倍率真实），静态表在那条路径上
//	根本不会被用到 —— 所以正常运行时**一个模型都不会少**。
//	只有 /v3 真挂了才会少，而那时给不出可信数据本就该少。
//
// ═══════════════════════════════════════════════════════════════════
// 保留 sortModelsByID 的理由
// ═══════════════════════════════════════════════════════════════════
//
//	它原先抽出来是给"补进静态模型后重新排序"用的，现在主流程
//	（models.go 的 Models()）仍然调用它 —— 排序保证 /v1/models
//	输出稳定可复现（便于测试与人工比对）。所以它**不是**静态表的遗留物，
//	删掉它会让模型顺序随上游返回顺序漂移。

// sortModelsByID 按对外 ID 排序（保证 /v1/models 输出稳定可复现）。
func sortModelsByID(models []provider.Model) {
	sort.Slice(models, func(i, j int) bool { return models[i].ID < models[j].ID })
}
